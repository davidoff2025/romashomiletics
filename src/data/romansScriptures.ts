/**
 * 根据课次获取对应的经文列表
 */
export function getVersesForLesson(lesson: Lesson): ScriptureVerse[] {
  if (lesson.isVacationBreak || !lesson.chapter) {
    return [];
  }

  // 特殊跨章处理：课17 罗马书 9:30-10:13
  if (lesson.id === '17') {
    const ch9 = (ROMANS_SCRIPTURES[9] || []).filter(v => v.verse >= 30);
    const ch10 = (ROMANS_SCRIPTURES[10] || []).filter(v => v.verse <= 13);
    return [...ch9, ...ch10];
  }

  const chapterVerses = ROMANS_SCRIPTURES[lesson.chapter] || [];
  if (!lesson.startVerse && !lesson.endVerse) {
    return chapterVerses;
  }

  const start = lesson.startVerse || 1;
  const end = lesson.endVerse || 999;

  const filtered = chapterVerses.filter(v => v.verse >= start && v.verse <= end);
  return filtered.length > 0 ? filtered : chapterVerses;
}
